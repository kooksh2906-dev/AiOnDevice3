#ifndef EDGESCOPE_LITE_CONFIG_H
#define EDGESCOPE_LITE_CONFIG_H

#include <stdint.h>
#include "xparameters.h"

/*
 * Prefer BSP-generated names.  The fallback values are not guesses: the B
 * block_design.tcl assigns and validates this exact frozen address map.
 */
#if defined(XPAR_PROBE_SAMPLER_0_BASEADDR)
#define EDGESCOPE_SAMPLER_BASEADDR XPAR_PROBE_SAMPLER_0_BASEADDR
#elif defined(XPAR_PROBE_SAMPLER_0_S_AXI_BASEADDR)
#define EDGESCOPE_SAMPLER_BASEADDR XPAR_PROBE_SAMPLER_0_S_AXI_BASEADDR
#else
#define EDGESCOPE_SAMPLER_BASEADDR 0x40010000u
#endif

#if defined(XPAR_BASIC_TRIGGER_ENGINE_0_BASEADDR)
#define EDGESCOPE_TRIGGER_BASEADDR XPAR_BASIC_TRIGGER_ENGINE_0_BASEADDR
#elif defined(XPAR_BASIC_TRIGGER_ENGINE_0_S_AXI_BASEADDR)
#define EDGESCOPE_TRIGGER_BASEADDR XPAR_BASIC_TRIGGER_ENGINE_0_S_AXI_BASEADDR
#else
#define EDGESCOPE_TRIGGER_BASEADDR 0x40020000u
#endif

#if defined(XPAR_CIRCULAR_TRACE_BUFFER_0_BASEADDR)
#define EDGESCOPE_TRACE_BASEADDR XPAR_CIRCULAR_TRACE_BUFFER_0_BASEADDR
#elif defined(XPAR_CIRCULAR_TRACE_BUFFER_0_S_AXI_BASEADDR)
#define EDGESCOPE_TRACE_BASEADDR XPAR_CIRCULAR_TRACE_BUFFER_0_S_AXI_BASEADDR
#else
#define EDGESCOPE_TRACE_BASEADDR 0x40030000u
#endif

#if defined(XPAR_AXI_BRAM_CTRL_CAPTURE_BASEADDR)
#define EDGESCOPE_BRAM_BASEADDR XPAR_AXI_BRAM_CTRL_CAPTURE_BASEADDR
#elif defined(XPAR_AXI_BRAM_CTRL_CAPTURE_S_AXI_BASEADDR)
#define EDGESCOPE_BRAM_BASEADDR XPAR_AXI_BRAM_CTRL_CAPTURE_S_AXI_BASEADDR
#elif defined(XPAR_XBRAM_0_BASEADDR)
#define EDGESCOPE_BRAM_BASEADDR XPAR_XBRAM_0_BASEADDR
#else
#define EDGESCOPE_BRAM_BASEADDR 0x42000000u
#endif

#if defined(XPAR_AXI_TIMER_0_BASEADDR)
#define EDGESCOPE_TIMER_BASEADDR XPAR_AXI_TIMER_0_BASEADDR
#elif defined(XPAR_XTMRCTR_0_BASEADDR)
#define EDGESCOPE_TIMER_BASEADDR XPAR_XTMRCTR_0_BASEADDR
#else
#error "AXI Timer base address was not generated by the BSP"
#endif

#define EDGESCOPE_TEST_CTRL_BASEADDR 0x40000000u
#define EDGESCOPE_CLOCK_HZ           100000000u
#define EDGESCOPE_UART_BAUD          9600u
#define EDGESCOPE_TIMEOUT_TICKS      20000000u
#define EDGESCOPE_INTER_TRIAL_TICKS  1000000u

#define EDGESCOPE_TEST_RISING       1u
#define EDGESCOPE_TEST_FALLING      2u
#define EDGESCOPE_TEST_PATTERN      3u
#define EDGESCOPE_TEST_PATTERN_HOLD 4u
#define EDGESCOPE_TEST_NO_TRIGGER   5u
#define EDGESCOPE_TEST_PULSE        6u

#endif
